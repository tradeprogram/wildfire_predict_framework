def img(path, cap, width='100%', maxh='150mm'):
    """세로로 긴 그림은 폭만 묶으면 페이지를 넘어가 앞 페이지가 통째로 빈다.
    높이도 함께 제한해 한 페이지에 반드시 들어가게 한다."""
    if not os.path.exists(path):
        return f'<p class="miss">[그림 없음: {os.path.basename(path)}]</p>'
    rel = 'file:///' + path.replace('\\', '/')
    return (f'<figure><img src="{rel}" style="max-width:{width};max-height:{maxh}">'
            f'<figcaption>{html.escape(cap)}</figcaption></figure>')


def table(headers, rows, widths=None):
    cols = ''.join(f'<col style="width:{w}">' for w in widths) if widths else ''
    th = ''.join(f'<th>{h}</th>' for h in headers)
    tr = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table>{cols}<thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table>'


def glossary(title, items):
    rows = [[f'<b>{t}</b>', d] for t, d in items]
    return f'<h3>{title}</h3>' + table(['용어', '뜻'], rows, ['26%', '74%'])


